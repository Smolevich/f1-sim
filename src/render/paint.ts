/**
 * Раскраска кузова по зонам.
 *
 * Модель безымянная: все 73 меша называются Object_N, материалов тоже 73 и все
 * чёрные, поэтому зона определяется геометрией — где деталь стоит на машине.
 *
 * Схема снята с реального болида: тёмный карбон несущий, а цвет команды идёт
 * крупными пятнами — нос, полоса по осевой до кокпита, законцовки антикрыльев,
 * борта понтонов. Ровная заливка одним цветом и делает машину похожей на
 * литую игрушку: у настоящей всегда работает контраст двух цветов.
 */
export type Zone = 'livery' | 'carbon' | 'wing' | 'accent' | 'floor'

export type Placement = {
  /** Центр детали в координатах модели. */
  x: number
  y: number
  z: number
  /** Габарит детали. */
  height: number
  width: number
}

/** Ось симметрии модели по X. */
const AXIS_X = 0.645

/** Пол машины: всё ниже этой высоты — карбоновое днище. */
const FLOOR_Y = 0.22

/** Halo и крышка двигателя. */
const CANOPY_Y = 0.68

/** Нос: от этой отметки вперёд идёт цветной обтекатель. */
const NOSE_Z = 0.95

/** Переднее антикрыло. */
const FRONT_WING_Z = 1.62

/** Заднее антикрыло и диффузор. */
const REAR_WING_Z = -1.72

/** Полоса по осевой: у Лего оранжевая лента идёт от носа через кокпит. */
const SPINE_HALF_WIDTH = 0.22

/** Законцовки антикрыльев: крайние по ширине пластины несут цвет команды. */
const ENDPLATE_OFFSET = 0.55

/** Полосой может быть только узкая деталь, а не кузов во всю ширину. */
const SPINE_MAX_WIDTH = 0.5

export function zoneFor(part: Placement): Zone {
  const offAxis = Math.abs(part.x - AXIS_X)

  // Антикрылья: пластины по краям цветные, сам профиль тёмный.
  if (part.z > FRONT_WING_Z || part.z < REAR_WING_Z) {
    return offAxis > ENDPLATE_OFFSET ? 'livery' : 'wing'
  }

  if (part.y < FLOOR_Y) return 'floor'
  if (part.y > CANOPY_Y) return 'carbon'

  // Нос целиком в цвете команды — самое заметное пятно спереди.
  if (part.z > NOSE_Z) return 'livery'

  // Полоса по осевой от носа до кокпита. Габарит обязателен: меш кузова
  // тянется через всю машину (1.78 м в ширину), центр у него тоже на осевой,
  // и без проверки ширины он забирал полосу — оранжевым заливало борта.
  if (offAxis < SPINE_HALF_WIDTH && part.width < SPINE_MAX_WIDTH) return 'livery'

  // Узкие накладки по борту — акцентный цвет.
  if (part.height < 0.16) return 'accent'

  return 'carbon'
}
