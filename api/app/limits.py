"""Планки трасс: предел самой модели физики, не реальные рекорды."""

from app.validation import TrackLimits

# Планка — нижняя граница: время быстрее неё отклоняется. Отсекать она должна
# невозможное, а не выдающееся, поэтому берётся заведомо ниже любого достижимого
# круга, а не близко к нему.
#
# Монца: 70 с на дистанции 5792 м требуют средней 298 км/ч — это 85% от
# максималки модели (352 км/ч на низкоприжимных крыльях с DRS), недостижимых на
# трассе с двумя шиканами. При этом планка ниже реального рекорда трассы
# (81.046 с), так что честный круг она не отклонит. Секторы разложены по тем же
# долям, что и sectorSplits [0.33, 0.62], и в сумме дают ровно планку круга —
# иначе посекторная и круговая проверки описывали бы разные заезды.
#
# Значения пересчитываются при любом изменении физики: модель станет быстрее —
# планка перестанет соответствовать пределу.
TRACK_LIMITS: dict[str, TrackLimits] = {
    "monza": TrackLimits(sim_record_ms=70_000, sim_sectors_ms=(23_100, 20_300, 26_600)),
}
